"use strict";

// One readable assembly shared by build and source lint. Keep source comments
// and ESLint directives here; only the emitted runtime is compacted.
function assembleBundle(bundle, fragments) {
  const wrappers = {
    global: ["", ""],
    workspace: ["(function () {\n", "})();\n"],
    periodic: ["(function (root) {\n", "})(globalThis);\n"],
    course: [
      '(function (root) {\n"use strict";\nroot.EduCourseUI = function (api) {\n',
      "};\n})(globalThis);\n",
    ],
    css: ["", ""],
  };
  if (!wrappers[bundle.scope])
    throw Error("Unknown source scope: " + bundle.scope);
  const [before, after] = wrappers[bundle.scope],
    prefix =
      (bundle.scope === "css"
        ? "/* Generated by npm run build; edit src/styles. */\n"
        : "// Generated by npm run build. Edit the source files listed in source-map.json.\n") +
      before,
    content = fragments
      .map(
        (fragment, index) =>
          (bundle.scope === "css"
            ? "/* Source: " + bundle.sources[index] + " */\n"
            : "// Source: " + bundle.sources[index] + "\n") + fragment,
      )
      .join("");
  return { prefix, code: prefix + content + after };
}

module.exports = { assembleBundle };
